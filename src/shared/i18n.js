  let override = null;

  function browserLang() {
    try {
      const ui = root.chrome && root.chrome.i18n && root.chrome.i18n.getUILanguage && root.chrome.i18n.getUILanguage();
      if (typeof ui === 'string' && ui.toLowerCase().startsWith('zh')) return 'zh';
      if (typeof ui === 'string') return 'en';
    } catch (_) {}
    return 'zh';
  }

  function lang() {
    if (override === 'zh' || override === 'en') return override;
    return browserLang();
  }

  function setOverride(value) {
    override = value === 'zh' || value === 'en' ? value : null;
    // Keep the decision-engine label for combined risk in sync with the UI.
    const coreApi = root.JevXBlocker;
    if (coreApi && coreApi.DECISION_LABELS) {
      coreApi.DECISION_LABELS.combined_risk = MESSAGES[lang()]['rule.combinedRisk'];
    }
    return override;
  }

  function has(key, targetLang) {
    const L = targetLang || lang();
    return Object.prototype.hasOwnProperty.call(MESSAGES[L], key);
  }

  function t(key, vars, targetLang) {
    const L = targetLang || lang();
    const dict = MESSAGES[L];
    let text = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key]
      : Object.prototype.hasOwnProperty.call(MESSAGES.zh, key) ? MESSAGES.zh[key]
      : key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) text = text.split('{' + k + '}').join(String(v));
    }
    return text;
  }

  // Fill static page text: data-i18n (textContent), data-i18n-placeholder,
  // data-i18n-title.
  function applyDocument(doc) {
    const document_ = doc || root.document;
    if (!document_ || !document_.querySelectorAll) return;
    document_.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    document_.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    document_.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    if (document_.documentElement) document_.documentElement.lang = lang() === 'en' ? 'en' : 'zh-CN';
  }

  const exported = {
    MESSAGES,
    t,
    has,
    lang,
    setOverride,
    applyDocument,
    browserLang
  };

  root.JevI18n = exported;
  if (typeof module !== 'undefined' && module.exports) module.exports = exported;
